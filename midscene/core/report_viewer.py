"""Single-file HTML report viewer for the IReportActionDump structure.

Upstream builds the official viewer (apps/report, a React app) and injects
it into core at build time; the Python SDK instead renders the same dump
structure with a self-contained vanilla-JS template, so reports stay
viewable without a Node build.
"""

import json
from pathlib import Path
from typing import Any, Dict, Optional

from loguru import logger

from .ai_model.env_config import get_midscene_run_dir

_TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>__TITLE__</title>
<style>
  * { box-sizing: border-box; }
  body { margin: 0; font-family: system-ui, -apple-system, sans-serif; background: #f5f6f8; color: #202124; }
  header { background: #1a1a2e; color: #fff; padding: 16px 24px; }
  header h1 { margin: 0; font-size: 18px; }
  header .meta { margin-top: 6px; font-size: 12px; color: #9aa0b5; }
  main { max-width: 1080px; margin: 24px auto; padding: 0 16px; }
  .exec { background: #fff; border: 1px solid #e0e2e8; border-radius: 12px; margin-bottom: 16px; overflow: hidden; }
  .exec > summary { cursor: pointer; padding: 12px 16px; font-weight: 600; font-size: 14px; display: flex; gap: 8px; align-items: center; }
  .exec[open] > summary { border-bottom: 1px solid #e0e2e8; }
  .badge { font-size: 11px; padding: 2px 8px; border-radius: 10px; font-weight: 500; }
  .badge.ok { background: #e6f4ea; color: #137333; }
  .badge.fail { background: #fce8e6; color: #c5221f; }
  .task { padding: 10px 16px; border-bottom: 1px solid #f0f1f4; font-size: 13px; }
  .task:last-child { border-bottom: none; }
  .task .head { display: flex; gap: 8px; align-items: center; }
  .task .type { color: #5f6368; font-size: 11px; text-transform: uppercase; letter-spacing: .04em; }
  .task pre { background: #f8f9fa; border-radius: 6px; padding: 8px; font-size: 12px; overflow-x: auto; margin: 6px 0 0; }
  .task .error { color: #c5221f; margin-top: 4px; white-space: pre-wrap; }
  .task img { max-width: 420px; border: 1px solid #e0e2e8; border-radius: 6px; margin-top: 6px; }
  .usage { color: #5f6368; font-size: 11px; margin-top: 4px; }
  .empty { text-align: center; color: #9aa0b5; padding: 40px; }
</style>
</head>
<body>
<header>
  <h1>__TITLE__</h1>
  <div class="meta">sdk __SDK__ · device __DEVICE__ · __GROUP__ · __COUNT__ executions · generated by Midscene Python</div>
</header>
<main id="app"></main>
<script id="midscene_report_dump" type="application/json">__DUMP__</script>
<script>
const dump = JSON.parse(document.getElementById('midscene_report_dump').textContent);
const app = document.getElementById('app');
const esc = (s) => String(s == null ? '' : s).replace(/[&<>"]/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'}[c]));
const badge = (status) => {
  const failed = ['failed', 'cancelled', 'error'].includes(String(status));
  return `<span class="badge ${failed ? 'fail' : 'ok'}">${esc(status || 'finished')}</span>`;
};
const findScreenshot = (value, depth = 0) => {
  if (!value || depth > 4) return null;
  if (typeof value === 'string' && value.startsWith('data:image')) return value;
  if (typeof value === 'string' && /^[A-Za-z0-9+/=]{200,}$/.test(value)) return 'data:image/png;base64,' + value;
  if (Array.isArray(value)) { for (const v of value) { const r = findScreenshot(v, depth + 1); if (r) return r; } }
  if (typeof value === 'object') { for (const k of Object.keys(value)) { const r = findScreenshot(value[k], depth + 1); if (r) return r; } }
  return null;
};
if (!dump.executions || !dump.executions.length) {
  app.innerHTML = '<div class="empty">No executions recorded.</div>';
} else {
  for (const exec of dump.executions) {
    const failed = exec.tasks && exec.tasks.some(t => t.status === 'failed');
    const details = document.createElement('details');
    details.className = 'exec';
    details.innerHTML = `<summary>${esc(exec.name || exec.id || 'execution')} <span class="badge ${failed ? 'fail' : 'ok'}">${failed ? 'failed' : 'success'}</span></summary>`;
    for (const task of exec.tasks || []) {
      const div = document.createElement('div');
      div.className = 'task';
      const status = task.status || 'finished';
      const param = task.param !== undefined ? JSON.stringify(task.param, null, 2) : '';
      const output = task.output !== undefined && task.output !== null ? JSON.stringify(task.output, null, 2) : '';
      const usage = task.usage ? `<div class="usage">tokens: ${task.usage.total_tokens ?? 0} (prompt ${task.usage.prompt_tokens ?? 0} / completion ${task.usage.completion_tokens ?? 0})</div>` : '';
      const logDump = task.log ? `<pre>${esc(JSON.stringify(task.log, null, 2).slice(0, 2000))}</pre>` : '';
      let screenshot = '';
      if (status !== 'finished') {
        div.querySelector; // noop to keep template simple
      }
      const shot = findScreenshot(task.uiContext) || findScreenshot(task.output && task.output.screenshot) || null;
      div.innerHTML = `
        <div class="head"><span class="type">${esc(task.type || '')}${task.subType ? ' / ' + esc(task.subType) : ''}</span> ${badge(status)} <span class="usage">${esc(task.errorMessage || '')}</span></div>
        ${param && param !== '{}' ? `<pre>${esc(param)}</pre>` : ''}
        ${output && output !== 'null' ? `<pre>${esc(output)}</pre>` : ''}
        ${logDump}
        ${usage}
        ${shot ? `<img src="${shot}">` : ''}
      `;
      details.appendChild(div);
    }
    app.appendChild(details);
  }
}
</script>
</body>
</html>
"""


def write_report_html(
    dump: Dict[str, Any],
    file_name: Optional[str] = None,
    run_dir: Optional[str] = None,
) -> Optional[str]:
    """Write `<midscene_run>/report/<name>.html` rendering the dump."""
    try:
        report_dir = Path(run_dir or get_midscene_run_dir("report"))
        report_dir.mkdir(parents=True, exist_ok=True)
        if not file_name:
            import time as _time
            import uuid as _uuid

            file_name = (
                f"report-{_time.strftime('%Y-%m-%d_%H-%M-%S')}-{_uuid.uuid4().hex[:8]}"
            )
        name = file_name.rsplit(".", 1)[0] if file_name.lower().endswith((".html", ".json")) else file_name

        group = str(dump.get("groupName", "Midscene Report"))
        title = f"{group} - {name}"
        safe_dump = json.dumps(dump, ensure_ascii=False).replace("</", "<\\/")
        html = (
            _TEMPLATE.replace("__TITLE__", title)
            .replace("__SDK__", str(dump.get("sdkVersion", "?")))
            .replace("__DEVICE__", str(dump.get("deviceType", "-")))
            .replace("__GROUP__", esc_html(group))
            .replace("__COUNT__", str(len(dump.get("executions", []))))
            .replace("__DUMP__", safe_dump)
        )
        path = report_dir / f"{name}.html"
        path.write_text(html, encoding="utf-8")
        logger.info(f"Midscene - HTML report written: {path}")
        return str(path)
    except Exception as e:
        logger.warning(f"failed to write HTML report: {e}")
        return None


def esc_html(text: str) -> str:
    return (
        str(text)
        .replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
    )
