"""Single-file HTML report viewer for the IReportActionDump structure.

Upstream builds the official viewer (apps/report, a React app) and injects
it into core at build time; the Python SDK instead renders the same dump
structure with a self-contained vanilla-JS template, so reports stay
viewable without a Node build.
"""

